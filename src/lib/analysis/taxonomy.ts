export function prettySkillName(key: string): string {
  const override = PRETTY_OVERRIDES[key];
  if (override) return override;
  return key
    .split(" ")
    .map((w) => (w.length <= 1 ? w.toUpperCase() : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(" ");
}

/* ── derived indexes ──────────────────────────────────────────── */

/** canonical lowercase skill key → alias list (aliases[0] === key). */
export const SKILL_TAXONOMY: Record<string, string[]> = {};

/** Flat, category-annotated skill entries in CATEGORY_ORDER order. */
export const ALL_SKILL_ENTRIES: SkillEntry[] = [];

for (const category of CATEGORY_ORDER) {
  const group = TAXONOMY[category] ?? {};
  for (const key of Object.keys(group)) {
    const aliases = group[key];
    if (!aliases || aliases.length === 0) continue;
    SKILL_TAXONOMY[key] = aliases;
    ALL_SKILL_ENTRIES.push({
      name: prettySkillName(key),
      category,
      aliases,
    });
  }
}

const ENTRY_BY_KEY: Record<string, SkillEntry> = {};
const ENTRY_BY_PRETTY: Record<string, SkillEntry> = {};
for (const entry of ALL_SKILL_ENTRIES) {
  ENTRY_BY_KEY[entry.aliases[0]] = entry;
  ENTRY_BY_PRETTY[entry.name.toLowerCase()] = entry;
}

/** Look up a skill entry by its pretty name OR its canonical key. */
export function findSkillEntry(name: string): SkillEntry | null {
  if (!name) return null;
  const byPretty = ENTRY_BY_PRETTY[name.toLowerCase()];
  if (byPretty) return byPretty;
  const byKey = ENTRY_BY_KEY[name.toLowerCase()];
  if (byKey) return byKey;
  return null;
}

/** Alias list for a skill (pretty name or canonical key). */
export function getSkillAliases(name: string): string[] {
  const entry = findSkillEntry(name);
  return entry ? entry.aliases : [name.toLowerCase()];
}

/** Category for a skill (pretty name or canonical key), or null. */
export function getSkillCategory(name: string): string | null {
  const entry = findSkillEntry(name);
  return entry ? entry.category : null;
}
